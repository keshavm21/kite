"""SASS opcode histograms: what ptxas / nvcc actually generated for each variant.

    python3 gpu/sass_opcodes.py [--kitec build/kitec] [--out results/sass_opcodes.md] [--arch sm_75]

Needs `ptxas`, `nvcc` and `cuobjdump` (all in /usr/local/cuda/bin on Colab). No GPU is used. For softmax_rows,
matmul_naive and matmul_tiled it builds Kite -O0, Kite -O1 without unrolling, Kite -O1 and the NVRTC/nvcc CUDA C
kernel, and prints how many SASS instructions of each opcode each one contains. This is how to tell *why* two
variants with the same instruction count (softmax -O0 vs -O1) or very different run times (matmul vs CUDA C)
differ, e.g. unrolled loops show up as fewer BRA/ISETP and more FFMA/FMUL/LDS.
"""
import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import bench  # noqa: E402  (its cupy import is lazy)

KERNELS = [
    ("softmax_rows", bench.CUDA_SOFTMAX),
    ("matmul_naive", bench.CUDA_MATMUL_NAIVE),
    ("matmul_tiled", bench.CUDA_MATMUL_TILED),
]


def opcodes(cubin: Path) -> Counter:
    out = subprocess.run(["cuobjdump", "-sass", str(cubin)], capture_output=True, text=True, check=True).stdout
    counts = Counter()
    for line in out.splitlines():
        m = re.match(r"^\s*/\*[0-9a-f]+\*/\s+(?:@!?U?P\w+\s+)?([A-Z][A-Z0-9_]*)", line)
        if m:
            counts[m.group(1)] += 1
    return counts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kitec", default=str(ROOT / "build" / "kitec"))
    ap.add_argument("--out", default=str(ROOT / "results" / "sass_opcodes.md"))
    ap.add_argument("--arch", default="sm_75")
    opts = ap.parse_args()
    for tool in ("ptxas", "nvcc", "cuobjdump"):
        if not shutil.which(tool):
            sys.exit(f"{tool} not found (on Colab: export PATH=$PATH:/usr/local/cuda/bin)")

    sections = ["# SASS opcode counts", "",
                f"Generated by `gpu/sass_opcodes.py` for `{opts.arch}` (do not edit by hand). Kite variants: PTX from `kitec`, assembled by `ptxas`. "
                "CUDA C: `nvcc -cubin -fmad=false`. Only opcodes that appear are listed; the total is every SASS instruction in the kernel.", ""]
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for name, cuda in KERNELS:
            src = ROOT / "examples" / f"{name}.kite"
            cols = {}
            for label, opt, extra, tag in (("Kite -O0", "-O0", (), ""), ("Kite -O1 no unroll", "-O1", ("--disable-pass=unroll",), "_nu"), ("Kite -O1", "-O1", (), "")):
                ptx = bench.kitec_ptx(Path(opts.kitec), src, opt, opts.arch, work, extra, tag)
                cubin = bench.cubin_from_ptx(ptx, opts.arch)
                cols[label] = opcodes(cubin)
            cubin = bench.cubin_from_cuda(cuda, name, opts.arch, work)
            cols["CUDA C (nvcc)"] = opcodes(cubin)
            names = sorted({op for c in cols.values() for op in c}, key=lambda op: -max(c[op] for c in cols.values()))
            sections += [f"## {name}", "", "| opcode | " + " | ".join(cols) + " |", "|---|" + "---:|" * len(cols)]
            for op in names:
                sections.append(f"| {op} | " + " | ".join(str(c[op]) if c[op] else "" for c in cols.values()) + " |")
            sections += [f"| **total** | " + " | ".join(f"**{sum(c.values())}**" for c in cols.values()) + " |", ""]
    text = "\n".join(sections)
    Path(opts.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
