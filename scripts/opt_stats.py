#!/usr/bin/env python3
"""Writes results/opt_stats.md: IR and PTX instruction counts of every example at -O0 vs -O1.

    python3 scripts/opt_stats.py [--kitec build/kitec] [-o results/opt_stats.md]

If `ptxas` is on PATH (e.g. on Colab) the table also lists the register count ptxas reports, which is what
actually matters on the GPU: ptxas re-optimizes the PTX, so a smaller PTX does not always mean faster SASS
(docs/PTX_BACKEND.md section 11).
"""
import argparse
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def kitec(binary, src, *flags):
    r = subprocess.run([str(binary), str(src), *flags], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"kitec {src} {' '.join(flags)} failed:\n{r.stderr}")
    return r.stdout


def ir_count(text):
    """Instructions in the IR text: indented lines that are not `shared` declarations."""
    return sum(1 for l in text.splitlines() if l.startswith("  ") and not l.startswith("  shared"))


def ptx_count(text):
    """PTX instructions: ';'-terminated lines in the kernel bodies, minus .reg declarations."""
    n, in_body = 0, False
    for l in text.splitlines():
        s = l.strip()
        if s == "{":
            in_body = True
        elif s == "}":
            in_body = False
        elif in_body and s.endswith(";") and not s.startswith(".reg"):
            n += 1
    return n


def registers(ptx_text):
    ptxas = shutil.which("ptxas")
    if not ptxas:
        return None
    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "k.ptx"
        f.write_text(ptx_text)
        r = subprocess.run([ptxas, "-arch=sm_75", "-v", str(f), "-o", "/dev/null"], capture_output=True, text=True)
    m = re.search(r"Used (\d+) registers", r.stderr)
    return int(m.group(1)) if m else None


def pct(a, b):
    return f"{100.0 * (b - a) / a:+.0f}%" if a else "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kitec", default=str(ROOT / "build/kitec"))
    ap.add_argument("-o", default=str(ROOT / "results/opt_stats.md"))
    args = ap.parse_args()
    have_ptxas = shutil.which("ptxas") is not None

    head = "| example | IR -O0 | IR -O1 | change | PTX -O0 | PTX -O1 | change |"
    sep = "|---|---:|---:|---:|---:|---:|---:|"
    if have_ptxas:
        head += " regs -O0 | regs -O1 |"
        sep += "---:|---:|"
    rows, totals = [], [0, 0, 0, 0]
    for src in sorted((ROOT / "examples").glob("*.kite")):
        ir0, ir1 = (ir_count(kitec(args.kitec, src, "--emit=ir", lvl)) for lvl in ("-O0", "-O1"))
        p0, p1 = (kitec(args.kitec, src, "--emit=ptx", lvl) for lvl in ("-O0", "-O1"))
        c0, c1 = ptx_count(p0), ptx_count(p1)
        for i, v in enumerate((ir0, ir1, c0, c1)):
            totals[i] += v
        row = f"| {src.stem} | {ir0} | {ir1} | {pct(ir0, ir1)} | {c0} | {c1} | {pct(c0, c1)} |"
        if have_ptxas:
            row += f" {registers(p0)} | {registers(p1)} |"
        rows.append(row)
    t = totals
    total = f"| **total** | {t[0]} | {t[1]} | {pct(t[0], t[1])} | {t[2]} | {t[3]} | {pct(t[2], t[3])} |"
    if have_ptxas:
        total += " | |"
    text = "\n".join([
        "# Optimizer results: -O0 vs -O1",
        "",
        "Instruction counts per example, generated by `scripts/opt_stats.py` (do not edit by hand).",
        "-O1 = `remove-unreachable, ssa, {constfold copyprop gvn dce simplifycfg} x<=4, licm gvn strength constfold dce simplifycfg, out-of-ssa`.",
        "",
        head, sep, *rows, total, "",
        "IR counts are instructions including terminators. PTX counts are body instructions (no `.reg` lines).",
        "A smaller PTX file is not necessarily faster code: ptxas runs its own optimizer, so compare registers and "
        "SASS too (`gpu/bench.py`, results in `bench_T4.md`).",
        "",
    ])
    Path(args.o).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
